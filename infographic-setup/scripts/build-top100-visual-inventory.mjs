#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { extname, resolve } from 'path';
import { spawnSync } from 'child_process';

const root = resolve(process.cwd());
const captionIndexPath = resolve(root, 'references/top100-caption-index.md');
const outMd = resolve(root, 'references/top100-visual-inventory.md');
const outHtml = resolve(root, 'references/top100-contact-sheet.html');

function parseRows(markdown) {
  const rows = [];

  for (const line of markdown.split('\n')) {
    if (!/^\|\s*\d+\s*\|/.test(line)) continue;
    const cols = line.split('|').slice(1, -1).map((col) => col.trim());
    if (cols.length < 7) continue;

    rows.push({
      ref: cols[0],
      image: cols[1].replace(/`/g, ''),
      openingType: cols[2],
      opener: cols[3],
      promise: cols[4],
      artifact: cols[5],
      saveTrigger: cols[6],
    });
  }

  return rows;
}

function dimsFor(imagePath) {
  if (!imagePath || imagePath.startsWith('(')) return null;
  const abs = resolve(root, imagePath);
  if (!existsSync(abs)) return null;

  const result = spawnSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', abs], {
    encoding: 'utf8',
  });

  if (result.status !== 0) return null;

  const width = Number(result.stdout.match(/pixelWidth:\s*(\d+)/)?.[1]);
  const height = Number(result.stdout.match(/pixelHeight:\s*(\d+)/)?.[1]);
  if (!width || !height) return null;

  return { width, height };
}

function orientation(dims) {
  if (!dims) return 'missing';
  if (dims.width === dims.height) return 'square';
  return dims.height > dims.width ? 'portrait' : 'landscape';
}

function aspect(dims) {
  if (!dims) return '';
  const ratio = dims.width / dims.height;
  if (Math.abs(ratio - 0.8) < 0.04) return '4:5';
  if (Math.abs(ratio - 0.625) < 0.04) return 'portrait tall';
  if (Math.abs(ratio - 1) < 0.04) return '1:1';
  if (Math.abs(ratio - 1.25) < 0.04) return '5:4';
  return `${dims.width}:${dims.height}`;
}

function route(row) {
  const text = `${row.openingType} ${row.artifact} ${row.opener} ${row.promise} ${row.saveTrigger}`.toLowerCase();
  const routes = [];

  if (/formula|metric|kpi|calculate|calculation|curve/.test(text)) routes.push('PF3 formula/KPI');
  if (/checklist|cheat|reference|guide|toolkit|list/.test(text)) routes.push('PF4 cheat-sheet/grid');
  if (/decision|choose|which|test|rule/.test(text)) routes.push('PF6 decision test/tree');
  if (/map|workflow|flow|system|connects|operational/.test(text)) routes.push('Process/map');
  if (/rank|index|exposure|roles|top/.test(text)) routes.push('PF7 ranked/index');
  if (/prompt|ai workflow|claude|copilot|chatgpt|gemini|tool/.test(text)) routes.push('AI workflow card');
  if (/framework|maturity|level|stages/.test(text)) routes.push('PF1/PF4 framework');
  if (/anatomy|inside|explained/.test(text)) routes.push('PF8 anatomy');

  return [...new Set(routes)].slice(0, 3).join('; ') || 'manual review';
}

function short(value, max = 82) {
  const clean = value.replace(/<br>/g, ' ').replace(/\s+/g, ' ').trim();
  return clean.length > max ? `${clean.slice(0, max - 1)}…` : clean;
}

function htmlEscape(value) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

const rows = parseRows(readFileSync(captionIndexPath, 'utf8')).map((row) => {
  const dims = dimsFor(row.image);
  return {
    ...row,
    dims,
    orientation: orientation(dims),
    aspect: aspect(dims),
    route: route(row),
    ext: row.image && !row.image.startsWith('(') ? extname(row.image).replace('.', '').toLowerCase() : '',
  };
});

const existingRows = rows.filter((row) => row.dims);
const orientationCounts = rows.reduce((acc, row) => {
  acc[row.orientation] = (acc[row.orientation] || 0) + 1;
  return acc;
}, {});
const routeCounts = rows.reduce((acc, row) => {
  for (const item of row.route.split('; ').filter(Boolean)) {
    acc[item] = (acc[item] || 0) + 1;
  }
  return acc;
}, {});

const md = `# Top-100 Visual Inventory

**Generated by:** \`scripts/build-top100-visual-inventory.mjs\`  
**Source:** \`references/top100-caption-index.md\`  
**Local images found:** ${existingRows.length} / ${rows.length}  
**Contact sheet:** \`references/top100-contact-sheet.html\`

Use this as the lean visual routing layer before opening individual reference files. It does not replace human visual inspection; it tells you which references are likely worth opening for a topic.

## Orientation Mix

${Object.entries(orientationCounts).sort().map(([key, value]) => `- ${key}: ${value}`).join('\n')}

## Inferred Route Mix

${Object.entries(routeCounts).sort((a, b) => b[1] - a[1]).map(([key, value]) => `- ${key}: ${value}`).join('\n')}

## Inventory

| Ref | Image | Size | Aspect | Opening | Artifact | Inferred visual route | Save trigger |
|---:|---|---|---|---|---|---|---|
${rows.map((row) => {
  const size = row.dims ? `${row.dims.width}x${row.dims.height}` : 'missing';
  const image = row.image.startsWith('(') ? row.image : `\`${row.image}\``;
  return `| ${row.ref} | ${image} | ${size} | ${row.aspect || 'missing'} | ${short(row.opener)} | ${short(row.artifact, 46)} | ${row.route} | ${short(row.saveTrigger, 56)} |`;
}).join('\n')}
`;

const htmlCards = rows.map((row) => {
  const img = row.dims
    ? `<img src="${htmlEscape(row.image.replace(/^references\//, ''))}" alt="Reference ${row.ref}">`
    : `<div class="missing">No local image</div>`;

  return `<article class="card">
    <div class="media">${img}</div>
    <div class="meta">
      <strong>#${row.ref}</strong>
      <span>${row.dims ? `${row.dims.width}x${row.dims.height} · ${row.aspect}` : 'missing'}</span>
    </div>
    <p>${htmlEscape(short(row.opener, 120))}</p>
    <small>${htmlEscape(row.route)}</small>
  </article>`;
}).join('\n');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Top-100 Reference Contact Sheet</title>
<style>
  body { margin: 0; font-family: Arial, sans-serif; background: #f3eddf; color: #09268f; }
  header { position: sticky; top: 0; z-index: 1; padding: 18px 24px; background: #09268f; color: #f3eddf; }
  h1 { margin: 0 0 4px; font-family: Georgia, serif; font-size: 32px; font-weight: 400; }
  header p { margin: 0; max-width: 920px; line-height: 1.4; }
  main { display: grid; grid-template-columns: repeat(auto-fill, minmax(220px, 1fr)); gap: 18px; padding: 24px; }
  .card { border: 1px solid rgba(9,38,143,.28); background: rgba(255,255,255,.48); min-width: 0; }
  .media { aspect-ratio: 4 / 5; display: grid; place-items: center; overflow: hidden; background: rgba(9,38,143,.08); }
  img { width: 100%; height: 100%; object-fit: contain; }
  .missing { font-weight: 700; opacity: .6; }
  .meta { display: flex; justify-content: space-between; gap: 8px; padding: 10px 10px 0; font-size: 12px; }
  p { margin: 8px 10px; min-height: 48px; font-size: 13px; line-height: 1.25; }
  small { display: block; padding: 0 10px 12px; color: #3552c7; line-height: 1.25; }
</style>
</head>
<body>
<header>
  <h1>Top-100 Reference Contact Sheet</h1>
  <p>Generated from local images plus caption index. Use this to shortlist references visually before opening individual files.</p>
</header>
<main>
${htmlCards}
</main>
</body>
</html>
`;

writeFileSync(outMd, md, 'utf8');
writeFileSync(outHtml, html, 'utf8');
console.log(`Wrote ${outMd.replace(root + '/', '')}`);
console.log(`Wrote ${outHtml.replace(root + '/', '')}`);
